const DICT: globalThis.Record<Lang, globalThis.Record<TranslationKey, string>> = { it: IT, en: EN };

/** Lingua predefinita della build: `en` per il pacchetto itch.io, `it` per il sito. */
export const DEFAULT_LANG: Lang = typeof __DEFAULT_LANG__ === "undefined" ? "it" : __DEFAULT_LANG__;

export const LANG_KEY = "scacchigramma-lang-v1";

/** Interpreta "it-IT", "en_US", "EN"… e restituisce una delle due lingue supportate. */
export function normalizeLang(value: string | null | undefined): Lang | null {
  if (!value) return null;
  const v = value.toLowerCase();
  if (v.startsWith("en")) return "en";
  if (v.startsWith("it")) return "it";
  return null;
}

/** Traduce una chiave, sostituendo i segnaposto `{nome}`. */
export function translate(lang: Lang, key: TranslationKey, params?: globalThis.Record<string, string | number>): string {
  const raw = DICT[lang][key] ?? DICT.it[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] === undefined ? match : String(params[name]),
  );
}
